#define NA51089_MUX_SETTING(_reg, _mask, _val) \
	{ \
		.reg = (_reg), \
		.mask = (_mask), \
		.val = (_val) + BUILD_BUG_ON_ZERO((_val) & ~(_mask)), \
	}

#define NA51089_MUX_GROUP(_name, _reg, _mask, _val, ...) \
	{ \
		.name = (_name), \
		.pins = (const uint[]){ __VA_ARGS__ }, \
		.npins = ARRAY_SIZE(((const uint[]){ __VA_ARGS__ })), \
		.settings = (const struct novatek_mux_setting[]){ \
			NA51089_MUX_SETTING(_reg, _mask, _val) \
		}, \
		.nsettings = 1, \
	}

#define NA51089_MUX_GROUP_NO_SETTINGS(_name, ...) \
	{ \
		.name = (_name), \
		.pins = (const uint[]){ __VA_ARGS__ }, \
		.npins = ARRAY_SIZE(((const uint[]){ __VA_ARGS__ })), \
	}

#define NA51089_PWM_GROUP(_name, _reg, _mask, _route, _pin) \
	NA51089_MUX_GROUP((_name), (_reg), (_mask), \
			    FIELD_PREP_CONST((_mask), (_route)), (_pin))

