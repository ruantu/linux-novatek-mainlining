static int na51089_get_pull_field(uint pin, struct novatek_pad_field *field)
{
	uint bank = NA51089_PIN_BANK(pin);
	uint offset = NA51089_PIN_OFFSET(pin);

	field->mask = NA51089_PAD_PULL_MASK;
	field->drive_type = NA51089_PAD_DRIVE_STANDARD;

	switch (bank) {
	case 0:
		if (offset > 22)
			return -ENOTSUPP;
		field->reg = offset < 16 ? NA51089_PAD_PULL_CGPIO0 :
					 NA51089_PAD_PULL_CGPIO1;
		field->shift = 2 * (offset & 0xf);
		break;
	case 1:
		if (offset <= 12) {
			field->reg = NA51089_PAD_PULL_PGPIO0;
			field->shift = 2 * offset;
		} else if (offset >= 17 && offset <= 24) {
			field->reg = NA51089_PAD_PULL_PGPIO1;
			field->shift = 2 * (offset - 16);
		} else {
			return -ENOTSUPP;
		}
		break;
	case 2:
		if (offset > 8)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_PULL_SGPIO;
		field->shift = 2 * offset;
		break;
	case 3:
		if (offset > 8)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_PULL_LGPIO;
		field->shift = 2 * offset;
		break;
	case 4:
		if (offset < 2 || offset > 7)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_PULL_DGPIO;
		field->shift = 2 * offset;
		break;
	case 5:
		if (offset > 11)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_PULL_HGPIO;
		field->shift = 2 * offset;
		break;
	case 6:
		if (offset > 2)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_PULL_AGPIO;
		field->shift = 2 * offset;
		break;
	case 7:
		if (offset > 10)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_PULL_DSIGPIO;
		field->shift = 2 * offset;
		break;
	default:
		return -ENOTSUPP;
	}
	field->mask <<= field->shift;

	return 0;
}

static int na51089_get_drive_field(uint pin, struct novatek_pad_field *field)
{
	uint bank = NA51089_PIN_BANK(pin);
	uint offset = NA51089_PIN_OFFSET(pin);

	field->drive_type = NA51089_PAD_DRIVE_STANDARD;
	field->mask = NA51089_PAD_DRIVE_MASK;

	switch (bank) {
	case 0:
		if (offset <= 10) {
			field->reg = NA51089_PAD_DRIVE_CGPIO0_OFS;
			field->shift = 2 * offset;
		} else if (offset <= 17) {
			field->reg = NA51089_PAD_DRIVE_CGPIO_HS_OFS;
			field->shift = 4 * (offset - 11);
			field->mask = NA51089_PAD_DRIVE_HS_MASK;
			field->drive_type = NA51089_PAD_DRIVE_HIGH_SPEED;
		} else if (offset <= 22) {
			field->reg = NA51089_PAD_DRIVE_CGPIO1_OFS;
			field->shift = 2 * (offset - 16);
		} else {
			return -ENOTSUPP;
		}
		break;
	case 1:
		if (offset <= 12) {
			field->reg = NA51089_PAD_DRIVE_PGPIO0_OFS;
			field->shift = 2 * offset;
		} else if (offset >= 17 && offset <= 25) {
			field->reg = NA51089_PAD_DRIVE_PGPIO1_OFS;
			field->shift = 2 * (offset - 16);
		} else {
			return -ENOTSUPP;
		}
		break;
	case 2:
		if (offset > 8)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_DRIVE_SGPIO_OFS;
		field->shift = 2 * offset;
		break;
	case 3:
		if (offset > 8)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_DRIVE_LGPIO_OFS;
		field->shift = 2 * offset;
		break;
	case 4:
		if (offset < 2 || offset > 7)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_DRIVE_DGPIO_OFS;
		field->shift = 2 * offset;
		break;
	case 5:
		if (offset > 11)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_DRIVE_HGPIO_OFS;
		field->shift = 2 * offset;
		if (offset <= 9)
			field->drive_type = NA51089_PAD_DRIVE_HGPIO;
		break;
	case 6:
		if (offset > 2)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_DRIVE_AGPIO_OFS;
		field->shift = 2 * offset;
		break;
	case 7:
		if (offset > 10)
			return -ENOTSUPP;
		field->reg = NA51089_PAD_DRIVE_DSIGPIO_OFS;
		field->shift = 2 * offset;
		break;
	default:
		return -ENOTSUPP;
	}
	field->mask <<= field->shift;

	return 0;
}

static int na51089_drive_to_raw(const struct novatek_pad_field *field,
				uint drive_ma, u32 *raw)
{
	switch (field->drive_type) {
	case NA51089_PAD_DRIVE_STANDARD:
		if (drive_ma < 4 || drive_ma > 16 || drive_ma % 4)
			return -EINVAL;
		*raw = drive_ma / 4 - 1;
		return 0;
	case NA51089_PAD_DRIVE_HIGH_SPEED:
		if (drive_ma < 3 || drive_ma > 24 || drive_ma % 3)
			return -EINVAL;
		*raw = drive_ma / 3 - 1;
		return 0;
	case NA51089_PAD_DRIVE_HGPIO:
		if (drive_ma == 4)
			*raw = NA51089_PAD_DRIVE_HGPIO_4MA;
		else if (drive_ma == 10)
			*raw = NA51089_PAD_DRIVE_HGPIO_10MA;
		else
			return -EINVAL;
		return 0;
	default:
		return -EINVAL;
	}
}

static uint na51089_raw_to_drive(const struct novatek_pad_field *field,
				 u32 raw)
{
	switch (field->drive_type) {
	case NA51089_PAD_DRIVE_STANDARD:
		return 4 * (raw + 1);
	case NA51089_PAD_DRIVE_HIGH_SPEED:
		return raw <= 7 ? 3 * (raw + 1) : 0;
	case NA51089_PAD_DRIVE_HGPIO:
		return raw <= NA51089_PAD_DRIVE_HGPIO_10MA ?
			(raw ? 10 : 4) : 0;
	default:
		return 0;
	}
}

