#ifndef __LINUX_MFD_NOVATEK_RTCSYS_H
#define __LINUX_MFD_NOVATEK_RTCSYS_H

#include <linux/bitfield.h>
#include <linux/bits.h>
#include <linux/mutex.h>

struct regmap;

#define RTC_TIMER_REG				0x00
#define RTC_DAYKEY_REG				0x04
#define RTC_ALARM_REG				0x08
#define RTC_STATUS_REG				0x0c
#define RTC_CTRL_REG				0x10
#define RTC_DATA_REG				0x14
#define RTC_PWBC_REG				0x18
#define RTC_PWBCSTS_REG				0x1c
#define RTC_PWRALM_REG				0x20
#define RTC_OSCAN_REG				0x24

/* RTC_TIMER bit fields */
#define RTC_TIMER_SECOND			GENMASK(5, 0)
#define RTC_TIMER_MINUTE			GENMASK(11, 6)
#define RTC_TIMER_HOUR				GENMASK(16, 12)
#define RTC_TIMER_TIME				GENMASK(16, 0)

/* RTC_DAYKEY bit fields */
#define RTC_DAYKEY_DAY				GENMASK(15, 0)
#define RTC_DAYKEY_KEY				GENMASK(19, 16)
#define RTC_DAYKEY_KEY_VALID			0xa
#define RTC_DAYKEY_KEY_POWER_LOST		BIT(0)

/* RTC_ALARM bit fields */
#define RTC_ALARM_SECOND			GENMASK(5, 0)
#define RTC_ALARM_MINUTE			GENMASK(11, 6)
#define RTC_ALARM_HOUR				GENMASK(16, 12)

/* RTC_STATUS bit fields */
#define RTC_STATUS_ALARM			BIT(0)
#define RTC_STATUS_SRST				BIT(1)
#define RTC_STATUS_READY			BIT(2)
#define RTC_STATUS_CSET				BIT(8)

/* RTC_CTRL bit fields */
#define RTC_CTRL_ALARM_INTEN			BIT(0)
#define RTC_CTRL_SRST				BIT(1)
#define RTC_CTRL_CSET				BIT(2)
#define RTC_CTRL_TIME_SEL			BIT(3)
#define RTC_CTRL_DAY_SEL			BIT(4)
#define RTC_CTRL_KEY_SEL			BIT(5)
#define RTC_CTRL_PWRALARMTIME_SEL		BIT(6)
#define RTC_CTRL_PWRALARMDAY_SEL		BIT(7)
#define RTC_CTRL_CSET_INTEN			BIT(8)
#define RTC_CTRL_DATA0_SEL			BIT(12)
#define RTC_CTRL_PWR_EN2_CONFIG			BIT(16)
#define RTC_CTRL_PWR_EN3_SEL			BIT(17)

/* RTC_DATA bit fields */
#define RTC_DATA_DATA0				GENMASK(7, 0)

/* RTC_PWBC bit fields */
#define RTC_PWBC_RESET_SDT_TIMER		BIT(0)
#define RTC_PWBC_PWR_OFF			BIT(1)
#define RTC_PWBC_PWRALARM_EN			BIT(3)
#define RTC_PWBC_PWRALARM_DIS			BIT(4)
#define RTC_PWBC_PWR_EN2_LATCH			BIT(5)
#define RTC_PWBC_PWR_EN3_CTRL			BIT(6)
#define RTC_PWBC_PWR_SW1_INTEN			BIT(24)
#define RTC_PWBC_PWR_SW2_INTEN			BIT(25)
#define RTC_PWBC_COMMAND				\
	(RTC_PWBC_RESET_SDT_TIMER |		\
	 RTC_PWBC_PWR_OFF |			\
	 RTC_PWBC_PWRALARM_EN |			\
	 RTC_PWBC_PWRALARM_DIS |			\
	 RTC_PWBC_PWR_EN2_LATCH)
#define RTC_PWBC_RESET_SDT_TIMER_CONFIG \
	(FIELD_PREP_CONST(RTC_PWBC_RESET_SDT_TIMER, 1) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_OFF, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWRALARM_EN, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWRALARM_DIS, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_EN2_LATCH, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_EN3_CTRL, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_SW1_INTEN, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_SW2_INTEN, 0))
#define RTC_PWBC_PWR_OFF_CONFIG \
	(FIELD_PREP_CONST(RTC_PWBC_RESET_SDT_TIMER, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_OFF, 1) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWRALARM_EN, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWRALARM_DIS, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_EN2_LATCH, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_EN3_CTRL, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_SW1_INTEN, 0) | \
	 FIELD_PREP_CONST(RTC_PWBC_PWR_SW2_INTEN, 0))

/* RTC_PWBCSTS bit fields */
#define RTC_PWBCSTS_PWRALARM_EN			BIT(0)
#define RTC_PWBCSTS_COREPWR_VALID		BIT(1)
#define RTC_PWBCSTS_PWRONSRC_SW1		BIT(8)
#define RTC_PWBCSTS_PWRONSRC_SW2		BIT(9)
#define RTC_PWBCSTS_PWRONSRC_SW3		BIT(10)
#define RTC_PWBCSTS_PWRONSRC_SW4		BIT(11)
#define RTC_PWBCSTS_PWRON_PWR_EN2		BIT(12)
#define RTC_PWBCSTS_PWRALARM_SRC		BIT(15)
#define RTC_PWBCSTS_PWR_SW1_PIN			BIT(16)
#define RTC_PWBCSTS_PWR_SW2_PIN			BIT(17)
#define RTC_PWBCSTS_PWR_SW3_PIN			BIT(18)
#define RTC_PWBCSTS_PWR_SW4_PIN			BIT(19)
#define RTC_PWBCSTS_PWR_SW1_STATUS		BIT(24)
#define RTC_PWBCSTS_PWR_SW2_STATUS		BIT(25)

/* RTC_PWRALM bit fields */
#define RTC_PWRALM_SECOND			GENMASK(5, 0)
#define RTC_PWRALM_MINUTE			GENMASK(11, 6)
#define RTC_PWRALM_HOUR				GENMASK(16, 12)
#define RTC_PWRALM_DAY				GENMASK(24, 20)

/* RTC_OSCAN bit fields */
#define RTC_OSCAN_CONFIG			GENMASK(7, 0)
#define RTC_OSCAN_CONFIG_DEFAULT		0x09
#define RTC_OSCAN_DEFAULT \
	(FIELD_PREP_CONST(RTC_OSCAN_CONFIG, RTC_OSCAN_CONFIG_DEFAULT))

enum novatek_rtcsys_irq {
	NOVATEK_RTCSYS_IRQ_ALARM,
	NOVATEK_RTCSYS_IRQ_CSET,
	NOVATEK_RTCSYS_IRQ_NUM,
};

struct novatek_rtcsys {
	struct regmap *regmap;
	struct mutex lock;
};

#endif /* __LINUX_MFD_NOVATEK_RTCSYS_H */
